# Compute ARCS dimension + subscale descriptive stats from Likert-type items
import pandas as pd
import numpy as np

# Identify ARCS item columns by prefix
arcs_prefixes = ['Attention:', 'Relevance:', 'Confidence:', 'Satisfaction:']
arcs_cols = [c for c in df.columns if any(c.startswith(p) for p in arcs_prefixes)]

# Coerce to numeric (Google Forms often stores Likert as numbers). Non-numeric become NaN.
df_arcs = df[arcs_cols].apply(pd.to_numeric, errors='coerce')

# Dimension mapping
dim_map = {}
for c in arcs_cols:
    for p in arcs_prefixes:
        if c.startswith(p):
            dim_map[c] = p.replace(':', '')
            break

dimensions = sorted(set(dim_map.values()), key=lambda x: ['Attention','Relevance','Confidence','Satisfaction'].index(x))

# Helper to compute summary stats
def summarize_items(frame):
    vals = frame.values.flatten()
    vals = vals[~np.isnan(vals)]
    if len(vals) == 0:
        return {'Items (n)': frame.shape[1], 'Mean (M)': np.nan, 'SD': np.nan, 'Min': np.nan, 'Max': np.nan}
    return {
        'Items (n)': frame.shape[1],
        'Mean (M)': float(np.nanmean(frame.values)),
        'SD': float(np.nanstd(frame.values, ddof=1)),
        'Min': float(np.nanmin(frame.values)),
        'Max': float(np.nanmax(frame.values)),
    }

# Dimension table
dim_rows = []
for dim in dimensions:
    cols_dim = [c for c, d in dim_map.items() if d == dim]
    stats = summarize_items(df_arcs[cols_dim])
    dim_rows.append({'ARCS Dimension / Subscale': dim, **stats})

dim_table = pd.DataFrame(dim_rows)

# Subscale table: treat each individual item as a subscale (common in ARCS reporting)
sub_rows = []
for c in arcs_cols:
    dim = dim_map[c]
    ser = df_arcs[c]
    sub_rows.append({
        'ARCS Dimension / Subscale': dim + ' / ' + c.replace(dim + ':', '').strip(),
        'Items (n)': 1,
        'Mean (M)': float(ser.mean(skipna=True)),
        'SD': float(ser.std(skipna=True, ddof=1)),
        'Min': float(ser.min(skipna=True)),
        'Max': float(ser.max(skipna=True)),
    })
sub_table = pd.DataFrame(sub_rows)

# Overall ARCS composite
overall_stats = summarize_items(df_arcs)
overall_table = pd.DataFrame([{'ARCS Dimension / Subscale': 'ARCS Overall', **overall_stats}])

print(dim_table)
print(overall_table)
print(sub_table.head())

