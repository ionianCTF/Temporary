# Helper stats
n_resp = resp_df.shape[0]

def cohens_d_one_sample(vals, mu0=5.0):
    vals = np.asarray(vals)
    return (vals.mean() - mu0) / vals.std(ddof=1)

# Effect sizes vs neutral midpoint (5 on a 0-10 scale)
effect_rows = []
for col in ['Attention','Relevance','Confidence','Satisfaction','ARCS_Overall','Perceived_Learning']:
    d_val = cohens_d_one_sample(resp_df[col].values, 5.0)
    effect_rows.append({'Composite': col, 'N': n_resp, 'Mean': resp_df[col].mean(), 'SD': resp_df[col].std(ddof=1), 'Cohen_d_vs5': d_val})

effect_df = pd.DataFrame(effect_rows)

