# Compute additional numeric results to support a fuller write-up (respondent-level composites, CIs, alphas, correlations)
import numpy as np
import pandas as pd

# --- Build respondent-level composites for each ARCS dimension ---
order_dims = ['Attention','Relevance','Confidence','Satisfaction']

dim_cols = {dim: [c for c, d in dim_map.items() if d == dim] for dim in order_dims}
dim_comp = pd.DataFrame({dim: df_arcs[dim_cols[dim]].mean(axis=1, skipna=True) for dim in order_dims})

# Overall ARCS composite (respondent mean across all items)
arcs_overall_comp = df_arcs.mean(axis=1, skipna=True)

# Perceived learning composite already computed as pl_composite

# --- Cronbach's alpha ---
def cronbach_alpha(frame):
    # frame: columns are items, rows are respondents
    frame2 = frame.dropna(axis=0, how='any')
    k = frame2.shape[1]
    if k < 2 or frame2.shape[0] < 3:
        return np.nan, frame2.shape[0]
    item_vars = frame2.var(axis=0, ddof=1)
    total_var = frame2.sum(axis=1).var(ddof=1)
    if total_var == 0:
        return np.nan, frame2.shape[0]
    alpha = (k / (k - 1.0)) * (1.0 - item_vars.sum() / total_var)
    return float(alpha), frame2.shape[0]

alpha_rows = []
for dim in order_dims:
    a, n_complete = cronbach_alpha(df_arcs[dim_cols[dim]])
    alpha_rows.append({'Scale': dim, 'Items': len(dim_cols[dim]), 'Alpha': a, 'N complete': n_complete})

pl_alpha, pl_ncomplete = cronbach_alpha(df_pl)
alpha_rows.append({'Scale': 'Perceived Learning', 'Items': df_pl.shape[1], 'Alpha': pl_alpha, 'N complete': pl_ncomplete})

alpha_table = pd.DataFrame(alpha_rows)

# --- Confidence intervals (95%) for respondent-level means ---
def mean_sd_ci(series):
    ser = pd.to_numeric(series, errors='coerce').dropna()
    n = ser.shape[0]
    m = float(ser.mean()) if n else np.nan
    sd = float(ser.std(ddof=1)) if n > 1 else np.nan
    se = sd / np.sqrt(n) if n > 1 else np.nan
    ci = 1.96 * se if n > 1 else np.nan
    return n, m, sd, (m - ci if n > 1 else np.nan), (m + ci if n > 1 else np.nan)

ci_rows = []
for dim in order_dims:
    n, m, sd, lo, hi = mean_sd_ci(dim_comp[dim])
    ci_rows.append({'Composite': dim, 'N': n, 'Mean': m, 'SD': sd, 'CI95 low': lo, 'CI95 high': hi})

n, m, sd, lo, hi = mean_sd_ci(arcs_overall_comp)
ci_rows.append({'Composite': 'ARCS Overall', 'N': n, 'Mean': m, 'SD': sd, 'CI95 low': lo, 'CI95 high': hi})

n, m, sd, lo, hi = mean_sd_ci(pl_composite)
ci_rows.append({'Composite': 'Perceived Learning', 'N': n, 'Mean': m, 'SD': sd, 'CI95 low': lo, 'CI95 high': hi})

ci_table = pd.DataFrame(ci_rows)

# --- Correlations between ARCS composites and learning impact ---
cor_rows = []
for dim in order_dims + ['ARCS Overall']:
    x = arcs_overall_comp if dim == 'ARCS Overall' else dim_comp[dim]
    y = pl_composite
    tmp = pd.concat([x, y], axis=1).dropna()
    if tmp.shape[0] >= 5:
        r = float(tmp.corr().iloc[0,1])
    else:
        r = np.nan
    cor_rows.append({'Predictor': dim, 'Outcome': 'Perceived Learning', 'Pearson r': r, 'N': int(tmp.shape[0])})
cor_table = pd.DataFrame(cor_rows)

print(alpha_table)
print(ci_table)
